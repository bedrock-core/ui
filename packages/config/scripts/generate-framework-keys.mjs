/**
 * Generate `src/frameworkGuideKeys.ts` from the bedrock-core resource pack's `.lang`.
 *
 * ## Why this exists
 *
 * `Text` resolves a `localizationKey` twice, for two different purposes. The CLIENT resolves it
 * against installed `.lang` files to paint the string; the LAYOUT ENGINE resolves it against
 * `TranslationKeysContext` to decide how big the box should be. A key present in the first but
 * missing from the second measures as the key itself — the box is sized for `bcg.x.y` and the
 * real sentence is painted into it, clipped.
 *
 * Addons never hit this: the `translation-keys` filter runs over each pack and its keys reach the
 * context through `core.register({ translations })`. bedrock-core has no realm and registers
 * nothing, so its keys have to arrive some other way — this file.
 *
 * ## Why generated rather than hand-written
 *
 * The two copies have to agree exactly or measurement silently goes wrong again, and nothing
 * would fail loudly when they drift. Deriving one from the other keeps `.lang` the single source
 * and makes drift impossible. Runs as part of `yarn build`; the output is committed because this
 * package ships TypeScript source, so consumers never run this script.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const LANG = join(HERE, '..', '..', 'resource-pack', 'packs', 'RP', 'texts', 'en_US.lang');
const OUT = join(HERE, '..', 'src', 'frameworkGuideKeys.ts');

/** Keys the framework renders itself. Everything else in that pack belongs to its own demo. */
const PREFIX = 'bcg.bedrock_core.';

const entries = readFileSync(LANG, 'utf8')
  .split(/\r?\n/)
  .filter(line => line.startsWith(PREFIX))
  .map((line) => {
    const eq = line.indexOf('=');

    if (eq === -1) { throw new Error(`malformed .lang line (no '='): ${line}`); }

    return [line.slice(0, eq), line.slice(eq + 1)];
  });

// An empty map would compile, ship, and clip every string in the guide with nothing to point at.
// A rename or a moved file should stop the build instead.
if (entries.length === 0) {
  throw new Error(`no '${PREFIX}*' keys found in ${LANG} — has the prefix or the file moved?`);
}

const body = entries.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join('\n');

writeFileSync(OUT, `/**
 * GENERATED by \`scripts/generate-framework-keys.mjs\` — do not edit.
 *
 * bedrock-core's own localization keys, mirrored from the resource pack's \`.lang\` so the layout
 * engine can measure them. See the script for why this is needed and why it is generated.
 *
 * Regenerate with \`yarn build\` in this package.
 */
export const frameworkGuideKeys: Record<string, string> = {
${body}
};
`);

console.log(`generate-framework-keys: ${String(entries.length)} keys -> src/frameworkGuideKeys.ts`);
